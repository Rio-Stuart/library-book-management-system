CREATE TABLE IF NOT EXISTS books (
    id VARCHAR(40) PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    author VARCHAR(150) NOT NULL,
    category VARCHAR(60) NOT NULL DEFAULT 'Computer Science',
    isbn VARCHAR(30) DEFAULT '',
    shelf_location VARCHAR(30) DEFAULT 'Rack A1',
    published_year INT DEFAULT 2024,
    available BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE books ADD COLUMN IF NOT EXISTS category VARCHAR(60) DEFAULT 'Computer Science';
ALTER TABLE books ADD COLUMN IF NOT EXISTS isbn VARCHAR(30) DEFAULT '';
ALTER TABLE books ADD COLUMN IF NOT EXISTS shelf_location VARCHAR(30) DEFAULT 'Rack A1';
ALTER TABLE books ADD COLUMN IF NOT EXISTS published_year INT DEFAULT 2024;

CREATE TABLE IF NOT EXISTS students (
    uid VARCHAR(40) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(120) DEFAULT '',
    department VARCHAR(80) DEFAULT 'Computer Science & Engineering',
    phone VARCHAR(25) DEFAULT ''
);

ALTER TABLE students ADD COLUMN IF NOT EXISTS email VARCHAR(120) DEFAULT '';
ALTER TABLE students ADD COLUMN IF NOT EXISTS department VARCHAR(80) DEFAULT 'Computer Science & Engineering';
ALTER TABLE students ADD COLUMN IF NOT EXISTS phone VARCHAR(25) DEFAULT '';

CREATE TABLE IF NOT EXISTS loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id VARCHAR(40) NOT NULL REFERENCES books(id),
    student_uid VARCHAR(40) NOT NULL REFERENCES students(uid),
    issued_on DATE NOT NULL,
    due_on DATE NOT NULL CHECK (due_on >= issued_on),
    returned_on DATE CHECK (returned_on >= issued_on),
    fine DECIMAL(12, 2) CHECK (fine >= 0),
    fine_paid BOOLEAN NOT NULL DEFAULT FALSE,
    renewed_count INT NOT NULL DEFAULT 0,
    CHECK ((returned_on IS NULL AND fine IS NULL) OR (returned_on IS NOT NULL AND fine IS NOT NULL))
);

ALTER TABLE loans ADD COLUMN IF NOT EXISTS fine_paid BOOLEAN DEFAULT FALSE;
ALTER TABLE loans ADD COLUMN IF NOT EXISTS renewed_count INT DEFAULT 0;

CREATE INDEX IF NOT EXISTS loans_student_index ON loans(student_uid);
CREATE INDEX IF NOT EXISTS loans_book_index ON loans(book_id);
